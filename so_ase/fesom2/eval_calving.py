# so_ase/fesom2/eval_calving.py

import os
import glob
import numpy as np
import xarray as xr
from .helpers_mesh import get_first_active_layer_area
from ..miscellaneous.helpers_misc import seconds_per_month

def fesom_antarctic_snowfall_flux(src_path, mesh_diag_path, year, savepath='./', log=False):
    """
    Compute and save the total Antarctic snowfall freshwater flux time series [m3/s]
    from FESOM2 output.

    This function loads the Antarctic snowfall flux field (`calving_AA`, [m/s]) from a
    FESOM2 output file (e.g. ``calving_AA.fesom.<year>.nc``), multiplies it by the nodal
    surface area from the mesh diagnostics file (`nod_area`), and sums over all nodes to
    obtain the total freshwater flux for each timestep. The result is saved as a
    standalone NetCDF file.

    Parameters
    ----------
    src_path : str
        Directory containing the FESOM calving output files named
        ``calving_AA.fesom.<year>.nc``.
    mesh_diag_path : str
        Directory containing ``fesom.mesh.diag.nc`` with `nod_area`.
    year : int
        Year to process.
    savepath : str, default './'
        Directory in which the output file is written. The file is created as
        ``snowfall_flux_AA.fesom.<year>.nc``.
    log : bool, default False
        If True, print a message whenever the file is saved or skipped.

    Returns
    -------
    str
        Path to the NetCDF file containing the ``snowfall_flux`` time series [m3/s].
    """
    print("\n--> Compute fesom antarctic snowfall flux...")

    out_file = f"{savepath}snowfall_flux_AA.fesom.{year}.nc"
    if os.path.exists(out_file):
        if log:
            print(f"Skipping existing file: {out_file}")
        return out_file

    os.makedirs(savepath, exist_ok=True)

    # Load mesh diagnostics and nodal area of the first active layer
    mesh_diag = xr.open_dataset(os.path.join(mesh_diag_path, 'fesom.mesh.diag.nc'))
    area = get_first_active_layer_area(mesh_diag)

    # Open file with cftime decoder
    time_coder = xr.coders.CFDatetimeCoder(use_cftime=True)
    ds = xr.open_mfdataset([f"{src_path}calving_AA.fesom.{year}.nc"], decode_times=time_coder, chunks={"time": 12})

    # Compute total snowfall freshwater flux [m3/s] for each timestep
    snowfall_flux = (ds.calving_AA * area).sum(dim='nod2')

    # Create output dataset
    ds_out = snowfall_flux.to_dataset(name='snowfall_flux')
    ds_out['snowfall_flux'].attrs = {
        'long_name': 'total Antarctic snowfall freshwater flux',
        'units': 'm3/s',
        'description': 'sum(calving_AA(i) [m/s] * area(i) [m2]) over all nodes'
    }
    ds_out.attrs['source'] = 'FESOM2'

    ds_out.to_netcdf(out_file)
    if log:
        print(f"Saved: {out_file}")

    return out_file

def snowfall_flux_to_massflux_Gty(src_path, dst_path, rho_fw=1000, year=None, log=True):
    """
    Convert monthly mean Antarctic snowfall flux time series (m3/s) into annual integrated
    mass fluxes (Gt/yr).

    This function reads the output files generated by ``fesom_antarctic_snowfall_flux()``,
    which contain a variable ``snowfall_flux`` representing monthly mean freshwater snowfall
    rates in m3/s. For each file, the freshwater flux is converted into an ice-mass-equivalent
    flux (kg/s), each monthly mean is multiplied by the number of seconds in that month
    (``seconds_per_month``, including leap years), and the result is summed over each year to
    obtain a total snowfall mass in gigatonnes per year (Gt/yr). A new NetCDF file with the
    suffix ``_GTY`` is written for each processed input file.

    Parameters
    ----------
    src_path : str
        Directory containing the files produced by ``fesom_antarctic_snowfall_flux()``
        named ``snowfall_flux_AA*.<year>.nc``.
    dst_path : str
        Directory for writing the output files.
    rho_fw : float, default 1000
        Density of freshwater in kg/m3. Used to convert freshwater volume flux (m3/s)
        into mass flux (kg/s).
    year : int, optional
        If specified, only process files for this year. If None, process all files.
    log : bool, default True
        If True, print progress messages when opening, skipping, or saving files.
    """
    print("\n--> Convert snowfall flux to massflux Gty...")

    os.makedirs(dst_path, exist_ok=True)
    pattern = f"snowfall_flux_AA*.{year}.nc" if year is not None else "snowfall_flux_AA*.nc"
    files2process = np.sort(glob.glob(os.path.join(src_path, pattern)))

    # Open files with cftime decoder
    time_coder = xr.coders.CFDatetimeCoder(use_cftime=True)

    for file in files2process:
        outfile = os.path.join(dst_path, os.path.basename(file).replace('snowfall_flux_AA', 'snowfall_flux_AA_GTY', 1))
        if os.path.exists(outfile):
            if log:
                print(f"Skipping: {file}")
            continue

        if log:
            print(f"Opening: {file}")
        ds_snowfall = xr.open_dataset(file, decode_times=time_coder)
        massflux_ice = ds_snowfall.snowfall_flux * rho_fw  # m3/s * kg/m3 = kg/s

        seconds = xr.DataArray(
            seconds_per_month(np.unique(massflux_ice.time.dt.year.values)),
            dims='time', coords={'time': massflux_ice.time}
        )
        Gty = (massflux_ice * seconds).groupby('time.year').sum() * 1e-12  # kg -> Gt

        ds_out = Gty.to_dataset(name='snowfall_flux_GTY')
        ds_out['snowfall_flux_GTY'].attrs = {
            'units': 'Gt/y',
            'long_name': 'Antarctic snowfall freshwater flux in Gigatons per year'
        }
        ds_out.to_netcdf(outfile)
        if log:
            print(f"Saved: {outfile}")

    return

